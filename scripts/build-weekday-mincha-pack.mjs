// Controlled import: turns the reviewed map into a content pack of fixed source offsets.
// Run: node scripts/build-weekday-mincha-pack.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import siddurOffline from '../src/data/siddurOffline.mjs';
import { normalizeHebrewText } from '../src/hebrewText.mjs';
import { checksum } from '../src/services/prayer/checksum.mjs';
import { MAP, SECTIONS } from './prayer-packs/edot-hamizrach-weekday-mincha.map.mjs';

const ROOT = 'Siddur Edot HaMizrach, Weekday Mincha';
const ROLES = new Set(['heading', 'recited', 'instruction', 'source', 'label']);
const fail = message => { throw new Error(message); };

// Text runs between <small>/<big>/<br> tags, with their raw-markup offsets.
export function markupPieces(markup) {
  const pieces = [];
  const token = /<\/?(?:small|big)\b[^>]*>|<br\s*\/?>/gi;
  let last = 0;
  let match;
  const push = (start, end) => {
    if (normalizeHebrewText(markup.slice(start, end), 'siddur')) pieces.push({ start, end });
  };
  while ((match = token.exec(markup))) {
    push(last, match.index);
    last = token.lastIndex;
  }
  push(last, markup.length);
  return pieces;
}

function parseSpec(spec, where) {
  const [role, when = null] = String(spec).split('@');
  if (!ROLES.has(role)) fail(`${where}: unknown role "${role}"`);
  return { role, when };
}

function heTitle(node) {
  return node.heTitle || node.titles?.find(title => title.lang === 'he' && title.primary)?.text || node.titles?.find(title => title.lang === 'he')?.text;
}

export function buildPack() {
  const rootNode = siddurOffline.schema.nodes.find(node => node.title === 'Weekday Mincha' || node.titles?.some(title => title.text === 'Weekday Mincha'));
  if (!rootNode) fail('Weekday Mincha root missing from the Siddur schema');
  const sections = SECTIONS.map(({ id, key }) => {
    const ref = `${ROOT}, ${key}`;
    const entry = siddurOffline.texts[ref];
    if (!entry?.he?.length) fail(`${ref}: no bundled text`);
    const node = rootNode.nodes.find(child => child.title === key || child.titles?.some(title => title.text === key));
    const map = MAP[id] || {};
    Object.keys(map).forEach(index => { if (!entry.he[index]) fail(`${ref}: map names missing segment ${index}`); });
    const blocks = [];
    entry.he.forEach((markup, segment) => {
      const spec = map[segment];
      const where = `${id}.${segment}`;
      if (spec === undefined) {
        if (/<(?:small|big)\b/i.test(markup)) fail(`${where}: segment has editorial markup but no reviewed mapping`);
        blocks.push({ id: where, segment, start: 0, end: markup.length, role: 'recited', when: null });
        return;
      }
      if (!Array.isArray(spec)) {
        blocks.push({ id: where, segment, start: 0, end: markup.length, ...parseSpec(spec, where) });
        return;
      }
      const pieces = markupPieces(markup);
      if (pieces.length !== spec.length) fail(`${where}: map lists ${spec.length} pieces, source has ${pieces.length}`);
      pieces.forEach((piece, index) => blocks.push({ id: `${where}.${index}`, segment, ...piece, ...parseSpec(spec[index], `${where}.${index}`) }));
    });
    return {
      id,
      ref,
      title: heTitle(node) || key,
      blocks: blocks.map(block => ({ ...block, checksum: checksum(entry.he[block.segment].slice(block.start, block.end)) })),
    };
  });
  const sample = siddurOffline.texts[`${ROOT}, Amida`];
  return {
    id: 'edot-hamizrach.weekday-mincha',
    version: '1.0.0',
    nusach: 'edot-hamizrach',
    prayer: 'mincha',
    dayType: 'weekday',
    source: {
      work: 'Siddur Edot HaMizrach',
      edition: sample.heVersionTitle.trim(),
      provider: 'Sefaria',
      license: sample.heLicense,
      url: 'https://www.sefaria.org/Siddur_Edot_HaMizrach',
      checkedAt: '2026-09-24',
    },
    sections,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pack = buildPack();
  const out = fileURLToPath(new URL('../src/data/prayerPacks/edotHaMizrachWeekdayMincha.mjs', import.meta.url));
  const body = `// Generated by scripts/build-weekday-mincha-pack.mjs from the reviewed map. Do not edit by hand.\nexport default ${JSON.stringify(pack, null, 1)};\n`;
  writeFileSync(out, body);
  const count = pack.sections.reduce((sum, section) => sum + section.blocks.length, 0);
  console.log(`wrote ${out}: ${pack.sections.length} sections, ${count} blocks`);
}
