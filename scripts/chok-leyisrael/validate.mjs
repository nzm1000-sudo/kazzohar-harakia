// Compares, day by day, what the חק לישראל packs contain with the refs of Sefaria's 378 "חק לישראל" sheets — a checking
// aid only: nothing is "fixed" from it. Torah, Nevi'im, Ketuvim (verse by verse), Mishnah (tractate and chapter) and
// Gemara (tractate, daf and amud where it begins). Writes its findings between the validation markers of
// docs/chok-leyisrael.md;  --check fails if that section is not current.
