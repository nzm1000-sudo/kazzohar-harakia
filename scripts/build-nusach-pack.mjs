// Turns a raw Sefaria dump (scripts/build-nusach-siddur.mjs) into a bundled, licence-checked siddur chunk:
//   node scripts/build-nusach-pack.mjs --nusach ashkenaz --dump /tmp/dump-ashkenaz.json
// Every leaf must carry a licence the app may redistribute (src/data/nusach/manifest.mjs, LICENSE_ALLOWLIST), or a
// version the manifest vouches for after checking its provenance by hand (Chabad: Sefaria's copy of the Hebrew
// Wikisource transcription of Siddur Torah Or). Anything else is left out and listed — a gap is reported, never hidden.
import { writeFileSync, readFileSync } from 'node:fs';
import { SIDDUR_SOURCES, LICENSE_ALLOWLIST, licenseAllowed } from '../src/data/nusach/manifest.mjs';

const args = Object.fromEntries(process.argv.slice(2).map((arg, i, list) => (arg.startsWith('--') ? [arg.slice(2), list[i + 1]] : null)).filter(Boolean));
const entry = SIDDUR_SOURCES[args.nusach];
if (!entry || !args.dump) { console.error('usage: --nusach <ashkenaz|sefard|chabad> --dump <dump.json>'); process.exit(1); }

const dump = JSON.parse(readFileSync(args.dump, 'utf8'));
if (dump.source.index !== entry.index) { console.error(`dump is ${dump.source.index}, manifest expects ${entry.index}`); process.exit(1); }

const texts = {};
const excluded = [...(dump.source.excludedLeaves || [])];
const versions = new Map();
for (const [ref, text] of Object.entries(dump.texts)) {
  const verdict = licenseAllowed(entry, text.heVersionTitle, text.heLicense);
  if (!verdict.ok) { excluded.push({ ref, why: `licence: ${text.heVersionTitle || '?'} · ${text.heLicense || 'none'}` }); continue; }
  // Empty paragraphs at the edges carry nothing; inner ones keep the edition's spacing.
  const he = text.he.map(paragraph => (typeof paragraph === 'string' ? paragraph : ''));
  if (!he.some(paragraph => paragraph.trim())) { excluded.push({ ref, why: 'blank' }); continue; }
  texts[ref] = { ref: text.ref, heRef: text.heRef, he, heVersionTitle: text.heVersionTitle, heVersionSource: text.heVersionSource, heLicense: verdict.license, primary_category: text.primary_category };
  const key = `${text.heVersionTitle} · ${verdict.license}`;
  versions.set(key, (versions.get(key) || 0) + 1);
}

// The schema keeps only what the app reads: titles, keys, depth — not Sefaria's address metadata.
const trim = node => ({
  ...(node.nodes ? { nodes: node.nodes.map(trim) } : { depth: node.depth }),
  title: node.title, heTitle: node.heTitle, key: node.key,
  titles: (node.titles || []).filter(item => item.primary).map(({ text, lang, primary }) => ({ text, lang, primary })),
});
const schema = { nodes: dump.schema.nodes.map(trim) };
const source = {
  index: entry.index, heTitle: dump.source.heTitle, nusach: args.nusach, provider: 'Sefaria', url: dump.source.url,
  accessedAt: dump.source.accessedAt, license: entry.license, versions: [...versions.entries()].map(([version, leaves]) => ({ version, leaves })),
  excludedLeaves: excluded, allowlist: LICENSE_ALLOWLIST,
};
const out = new URL(`../src/data/nusach/${entry.file}`, import.meta.url);
writeFileSync(out, `// Generated by scripts/build-nusach-pack.mjs from Sefaria "${entry.index}" — do not edit by hand.\n// Licence and attribution: src/data/nusach/manifest.mjs. Loaded on demand (its own chunk), never on app start.\nexport default ${JSON.stringify({ source, schema, texts })};\n`);
console.log(entry.index, '→', out.pathname, '·', Object.keys(texts).length, 'texts ·', excluded.length, 'excluded');
for (const [version, count] of versions) console.log('  ', version, '×', count);
for (const item of excluded) console.log('   excluded:', item.ref, '·', item.why);
