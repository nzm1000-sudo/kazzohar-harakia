// Builds src/data/talmudChapters.mjs: every tractate's chapters (Hebrew name, number, first and last amud) from the
// "Chapters" structure of Sefaria's index for that tractate. Bundled so the chapter list works offline.
// Run: node scripts/build-talmud-chapters.mjs
import { writeFileSync } from 'node:fs';
import catalog from '../src/data/talmudCatalog.mjs';

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const amudOf = ref => (String(ref).match(/(\d+[ab])/) || [])[1] || null;
const out = {};
for (const tractate of catalog.tractates.filter(t => t.steinsaltz)) {
  const index = await (await fetch(`https://www.sefaria.org/api/v2/raw/index/${encodeURIComponent(tractate.title)}`)).json();
  const nodes = index.alt_structs?.Chapters?.nodes || [];
  out[tractate.title] = nodes.map((node, i) => {
    const [from, to] = String(node.wholeRef).replace(`${tractate.title} `, '').split('-');
    return { n: i + 1, name: (node.titles?.find(t => t.lang === 'he' && t.primary) || node.titles?.find(t => t.lang === 'he'))?.text?.trim() || '', start: amudOf(from), end: amudOf(to || from) || amudOf(from) };
  });
  if (!out[tractate.title].length) throw new Error(`no chapters for ${tractate.title}`);
  await sleep(150);
}
writeFileSync(new URL('../src/data/talmudChapters.mjs', import.meta.url), `// Generated by scripts/build-talmud-chapters.mjs from the "Chapters" structure of Sefaria's Talmud indexes.\n// { Tractate: [{ n, name, start, end }] } — start/end are the amudim where the chapter begins and ends.\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'tractates', Object.values(out).reduce((sum, list) => sum + list.length, 0), 'chapters');
