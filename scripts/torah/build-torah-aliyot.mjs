// Builds src/data/torahAliyot.mjs: the seven aliyot of every weekly parasha (and of the combined readings), from
// @hebcal/leyning's full-kriyah tables (BSD-2-Clause; the library behind hebcal.com). Used by the Shnayim Mikra reader
// (a link straight to one aliya) and by the Jewish reminder (המזכיר היהודי: one aliya a day, Sunday to Friday).
// @hebcal/leyning is not an app dependency: install it in a scratch folder and pass its path.
//   node scripts/torah/build-torah-aliyot.mjs /path/to/node_modules/@hebcal/leyning
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { SHNAYIM_MIKRA_CANONICAL_RANGES } from '../../src/data/shnayimMikraRanges.mjs';

const dir = process.argv[2];
if (!dir) throw new Error('usage: build-torah-aliyot.mjs <path to @hebcal/leyning>');
const pkg = JSON.parse(await (await import('node:fs/promises')).readFile(`${dir}/package.json`, 'utf8'));
const { getLeyningForParsha } = await import(pathToFileURL(`${dir}/dist/esm/index.js`).href);
const out = {};
for (const reading of SHNAYIM_MIKRA_CANONICAL_RANGES) {
  const names = reading.combined ? reading.name.split('-').map(part => part.replace(/’/g, "'")) : reading.name.replace(/’/g, "'");
  const leyning = getLeyningForParsha(names);
  const aliyot = [];
  for (let n = 1; n <= 7; n += 1) {
    const aliya = leyning.fullkriyah[String(n)];
    if (!aliya || aliya.k !== reading.reference.split(' ')[0]) throw new Error(`${reading.id}: aliya ${n}`);
    aliyot.push([aliya.b, aliya.e]);
  }
  out[reading.id] = aliyot;
}
const body = `// Generated by scripts/torah/build-torah-aliyot.mjs from @hebcal/leyning ${pkg.version} (${pkg.license}), full-kriyah aliyot.
// Do not edit by hand. { parashaId: [[begin "chapter:verse", end "chapter:verse"] × 7] } — ids as in shnayimMikraRanges.mjs.
export const TORAH_ALIYOT_SOURCE = Object.freeze({ library: '@hebcal/leyning', version: ${JSON.stringify(pkg.version)}, license: ${JSON.stringify(pkg.license)} });
export const TORAH_ALIYOT = Object.freeze(${JSON.stringify(out)});
`;
writeFileSync(new URL('../../src/data/torahAliyot.mjs', import.meta.url), body);
console.log(Object.keys(out).length, 'readings');
