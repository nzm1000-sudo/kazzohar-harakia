// Builds src/data/dvarTorahExcerpts.mjs: for every weekly parasha, a handful of short excerpts from the public-domain
// commentaries already bundled in the app (public/library/packs/sefaria-tanakh-commentary-public-domain) — the opening
// verse of the parasha and the first verses of its aliyot. Nothing is written or rewritten: each excerpt is the
// beginning of one comment, cut only at the end of a sentence (or kept whole), exactly as in the bundled edition, with
// its commentator, place and the pack unit it comes from. tests/mazkir.test.mjs checks every excerpt against the pack.
//   node scripts/torah/build-dvar-torah-excerpts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import COMMENTARY from '../../src/data/library/corpus/tanakhCommentary.mjs';
import { SHNAYIM_MIKRA_CANONICAL_RANGES } from '../../src/data/shnayimMikraRanges.mjs';
import { TORAH_ALIYOT } from '../../src/data/torahAliyot.mjs';

const PACK = 'sefaria-tanakh-commentary-public-domain';
// Commentators whose words read well on their own at a Shabbat table (Rashi's companions — Siftei Chakhamim, Ibn Ezra's
// grammar — are left to the library).
const COMMENTATORS = ['Kli_Yakar', 'Or_HaChaim', 'Sforno', 'Ramban', 'Haamek_Davar', 'Rabbeinu_Bahya', 'Rashbam', 'Tur_HaArokh'];
const MAX = 620;
const MIN_CUT = 220;
const MIN_LENGTH = 260;
const PER_PARASHA = 6;

const works = new Map(COMMENTARY.packs.find(pack => pack.packId === PACK).works.map(work => [work.workId, work]));
const cache = new Map();
function load(workId) {
  if (!cache.has(workId)) {
    let json = null;
    try { json = JSON.parse(gunzipSync(readFileSync(new URL(`../../public/library/packs/${PACK}/${workId}.json.gz`, import.meta.url))).toString('utf8')); } catch { json = null; }
    cache.set(workId, json);
  }
  return cache.get(workId);
}
// The beginning of a comment, whole when short, otherwise up to the last sentence end within MAX characters.
export function excerptOf(text) {
  if (text.length <= MAX) return { text, complete: true };
  const window = text.slice(0, MAX);
  let cut = -1;
  for (const match of window.matchAll(/[.:](?=\s|$)/g)) if (match.index + 1 >= MIN_CUT) cut = match.index + 1;
  return cut > 0 ? { text: text.slice(0, cut), complete: false } : null;
}
const parse = ref => ref.split(':').map(Number);
const out = {};
for (const reading of SHNAYIM_MIKRA_CANONICAL_RANGES.filter(item => !item.combined)) {
  const book = reading.reference.split(' ')[0];
  const aliyot = TORAH_ALIYOT[reading.id];
  const places = aliyot.map(([begin]) => parse(begin));
  const index = SHNAYIM_MIKRA_CANONICAL_RANGES.indexOf(reading);
  // Vary who opens from week to week.
  const order = COMMENTATORS.map((_, i) => COMMENTATORS[(i + index) % COMMENTATORS.length]);
  const used = new Set();
  const chosen = [];
  for (const [chapter, verse] of places) {
    if (chosen.length >= PER_PARASHA) break;
    let picked = null;
    for (const name of order) {
      if (used.has(name)) continue;
      const workId = `${name}_on_${book}`;
      const work = works.get(workId);
      const json = work && load(workId);
      if (!json) continue;
      const node = json.nodes.find(item => item.n === chapter);
      // The first comment on this verse or the two after it, long enough to say something.
      const unit = node?.units.find(item => item.v >= verse && item.v <= verse + 2 && item.text.length >= MIN_LENGTH && !/^(?:ו?עוד|ואפשר|וְאֶפְשָׁר|וְעוֹד)\b/.test(item.dh || ''));
      if (!unit) continue;
      const excerpt = excerptOf(unit.text);
      if (!excerpt) continue;
      picked = { workId, unitId: unit.id, commentator: work.layerTitle, sourceLine: work.sourceLine, chapter, verse: unit.v, dh: unit.dh || null, text: excerpt.text, complete: excerpt.complete };
      used.add(name);
      break;
    }
    if (picked) chosen.push(picked);
  }
  out[reading.id] = chosen;
}
const body = `// Generated by scripts/torah/build-dvar-torah-excerpts.mjs from the app's bundled public-domain commentaries
// (${PACK}, Sefaria exports). Do not edit by hand: every text is an exact excerpt of the pack unit named beside it.
export const DVAR_TORAH_EXCERPTS = Object.freeze(${JSON.stringify(out)});
`;
writeFileSync(new URL('../../src/data/dvarTorahExcerpts.mjs', import.meta.url), body);
console.log(Object.keys(out).length, 'parashot', Object.values(out).reduce((n, list) => n + list.length, 0), 'excerpts', Buffer.byteLength(body), 'bytes');
