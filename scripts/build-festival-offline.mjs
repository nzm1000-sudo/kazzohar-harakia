// Builds src/data/festivalOffline.mjs: festival texts outside the siddur that may be bundled — only public-domain
// editions (checked here, the build stops otherwise). Stored in the shape the Sefaria texts API returns, so the reader
// treats them exactly like an online answer. Run: node scripts/build-festival-offline.mjs
import { writeFileSync } from 'node:fs';

const REFS = ['Selichot Edot HaMizrach'];
const texts = {};
for (const ref of REFS) {
  const data = await (await fetch(`https://www.sefaria.org/api/texts/${encodeURIComponent(ref)}?context=0&commentary=0`)).json();
  if (!/public domain|cc0/i.test(data.heLicense || '')) throw new Error(`${ref}: licence "${data.heLicense}" is not public domain`);
  if (!Array.isArray(data.he) || !data.he.length) throw new Error(`${ref}: empty`);
  texts[ref] = { ref: data.ref, heRef: data.heRef, he: data.he, heVersionTitle: data.heVersionTitle, heVersionSource: data.heVersionSource, heLicense: data.heLicense, primary_category: data.primary_category };
  console.log(ref, data.he.length, 'paragraphs ·', data.heVersionTitle, '·', data.heLicense);
}
writeFileSync(new URL('../src/data/festivalOffline.mjs', import.meta.url), `// Generated by scripts/build-festival-offline.mjs — public-domain festival texts bundled for offline use.\nexport default ${JSON.stringify({ texts })};\n`);
