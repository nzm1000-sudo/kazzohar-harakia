// One-time catalog build: Bavli tractates, amud counts, and Steinsaltz Hebrew availability.
// Output: src/data/talmudCatalog.mjs  (run: node scripts/build-talmud-catalog.mjs)
import { writeFileSync } from 'node:fs';
const get = async p => (await fetch('https://www.sefaria.org/api' + p)).json();
const shape = await get('/shape/Talmud/Bavli');
const out = [];
for (const t of shape) {
  if (!t.chapters || !t.title) continue;
  const versions = await get('/texts/versions/' + encodeURIComponent('Steinsaltz on ' + t.title)).catch(() => []);
  const steinsaltz = Array.isArray(versions) ? versions.find(v => v.language === 'he') : null;
  const baseVersions = await get('/texts/versions/' + encodeURIComponent(t.title)).catch(() => []);
  const base = Array.isArray(baseVersions) ? baseVersions.find(v => v.language === 'he' && /Vocalized/.test(v.versionTitle)) || baseVersions.find(v => v.language === 'he') : null;
  const amudim = t.chapters.map((n, i) => n > 0 ? i : -1).filter(i => i >= 0);
  const first = amudim[0], last = amudim[amudim.length - 1];
  const amud = i => `${Math.floor(i / 2) + 1}${i % 2 === 0 ? 'a' : 'b'}`;
  out.push({
    title: t.title, heTitle: t.heTitle, seder: t.section, book: t.book,
    firstAmud: amud(first), lastAmud: amud(last), amudCount: amudim.length,
    segmentsPerAmud: t.chapters,
    baseVersion: base ? { title: base.versionTitle, license: base.license } : null,
    steinsaltz: steinsaltz ? { index: 'Steinsaltz on ' + t.title, version: steinsaltz.versionTitle, license: steinsaltz.license } : null,
  });
  process.stdout.write(`${t.title}: ${t.heTitle} ${amud(first)}–${amud(last)} steinsaltz=${steinsaltz ? 'yes' : 'NO'}\n`);
}
writeFileSync(new URL('../src/data/talmudCatalog.mjs', import.meta.url), '// Generated by scripts/build-talmud-catalog.mjs from Sefaria shape + versions APIs.\nexport default ' + JSON.stringify({ generated: new Date().toISOString().slice(0, 10), source: 'https://www.sefaria.org/api/shape/Talmud/Bavli', tractates: out }, null, 1) + ';\n');
console.log('tractates', out.length, 'with steinsaltz', out.filter(t => t.steinsaltz).length);
