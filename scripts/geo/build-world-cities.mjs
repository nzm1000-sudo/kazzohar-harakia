// Builds src/data/worldCities.mjs — the offline city list of "זמנים בכל העולם" (travel mode) — from GeoNames'
// cities15000 dump (https://download.geonames.org/export/dump/cities15000.zip, CC BY 4.0, © GeoNames).
// Kept to a meaningful size: every city of 300,000 and more, every national capital, every place in Israel (and the
// areas of Judea, Samaria and Gaza) of 15,000 and more, and a short list of Jewish community centres.
// Hebrew names: the Hebrew label of the place's Wikidata item (CC0), matched by its GeoNames id (Wikidata P1566) — a
// JSON map {geonameid: label} made by scripts/geo/fetch-hebrew-labels.py; a place without one shows its English name.
// Usage: node scripts/geo/build-world-cities.mjs <cities15000.txt> <retrievedAt YYYY-MM-DD> [he-labels.json] [--ids]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2).filter(arg => arg !== '--ids');
const idsOnly = process.argv.includes('--ids');
const [input, retrievedAt = new Date().toISOString().slice(0, 10), labelsPath] = args;
const LABELS = labelsPath ? JSON.parse(readFileSync(labelsPath, 'utf8')) : {};
if (!input) { console.error('usage: build-world-cities.mjs <cities15000.txt> [YYYY-MM-DD]'); process.exit(1); }
const MIN_POPULATION = 300000;
const ISRAEL_MIN = 15000;
// Jewish community centres below the general threshold (ASCII name + country code as in GeoNames).
const COMMUNITIES = new Set(['Lakewood|US', 'Teaneck|US', 'Passaic|US', 'Monsey|US', 'Boca Raton|US', 'Miami Beach|US', 'Beverly Hills|US', 'Skokie|US', 'Gateshead|GB', 'Salford|GB', 'Antwerpen|BE', 'Uman|UA', 'Strasbourg|FR', 'Nice|FR', 'Sarcelles|FR', 'Houmt Souk|TN', 'Great Neck|US', 'Deal|US', 'Cedarhurst|US', 'Spring Valley|US', 'Toms River|US', 'Kiryas Joel|US', 'Bnei Brak|IL', 'Hampstead|CA', 'Cote-Saint-Luc|CA', 'Thornhill|CA', 'Golders Green|GB', 'Stamford Hill|GB', 'Bat Yam|IL']);
const HEBREW = /[\u05D0-\u05EA]/;

const rows = [];
for (const line of readFileSync(input, 'utf8').split('\n')) {
  if (!line.trim()) continue;
  const f = line.split('\t');
  const [id, name, ascii, lat, lon, featureCode, cc] = [f[0], f[1], f[2], f[4], f[5], f[7], f[8]];
  const population = Number(f[14]) || 0;
  const tz = f[17];
  const israel = cc === 'IL' || cc === 'PS';
  const keep = population >= MIN_POPULATION || featureCode === 'PPLC' || (israel && population >= ISRAEL_MIN) || COMMUNITIES.has(`${ascii}|${cc}`);
  if (!keep || !tz) continue;
  const label = String(LABELS[id] || '').trim();
  const he = HEBREW.test(label) ? label.replace(/\s*\(.*\)\s*$/, '').split(',')[0].trim() : '';
  rows.push({ id: Number(id), name: ascii || name, he: he.trim(), cc, lat: Number(lat).toFixed(4), lon: Number(lon).toFixed(4), tz, population });
}
rows.sort((a, b) => b.population - a.population || a.id - b.id);
if (idsOnly) { console.log(rows.map(row => row.id).join('\n')); process.exit(0); }
const lines = rows.map(row => JSON.stringify([row.name, row.he, row.cc, row.lat, row.lon, row.tz, row.population].join('|')));
const out = `// Generated by scripts/geo/build-world-cities.mjs from GeoNames cities15000 — do not edit.
// Source: GeoNames (https://www.geonames.org/), licence CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Retrieved ${retrievedAt}. ${rows.length} places: cities of ${MIN_POPULATION.toLocaleString('en')}+, national capitals, places in Israel of ${ISRAEL_MIN.toLocaleString('en')}+, and Jewish community centres.
// Hebrew names: Wikidata labels (CC0) matched by GeoNames id.
// Each row: name|Hebrew name (may be empty)|country|latitude|longitude|timezone|population.
export const WORLD_CITIES_SOURCE = Object.freeze({ hebrewNames: 'Wikidata labels (CC0), by GeoNames id', name: 'GeoNames', url: 'https://www.geonames.org/', license: 'CC BY 4.0', licenseUrl: 'https://creativecommons.org/licenses/by/4.0/', dataset: 'cities15000', retrievedAt: '${retrievedAt}', count: ${rows.length} });
export const WORLD_CITIES = [
${lines.join(',\n')},
];
`;
writeFileSync(fileURLToPath(new URL('../../src/data/worldCities.mjs', import.meta.url)), out);
console.log(`${rows.length} places written`);
