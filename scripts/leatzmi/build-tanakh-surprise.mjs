// Generates what פסוק בהפתעה and מילה בהפתעה need, from the bundled Tanakh (public/library/packs/uxlc-2.5, UXLC 2.5 ·
// Tanach.us):
//   src/data/leatzmi/tanakhVerses.mjs  BOOKS: [[workId, hebrewName, section, [verses in chapter 1, 2, …]]] — every
//                                      verse of the Tanakh is reachable (small; the verse wheel's catalogue);
//   src/data/leatzmi/tanakhWords.mjs   WORDS: [[word, bookIndex, chapter, verse]] — one meaningful word per entry, with
//                                      its nikud exactly as that verse has it (te'amim removed), from the verse named.
// Deterministic: the same pack gives the same file. Run: node scripts/leatzmi/build-tanakh-surprise.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { TANAKH_SECTIONS } from '../../src/data/tanakhCatalog.mjs';
import { baseLetters, isMeaningfulShape, looksPrefixed, verseWords } from '../../src/services/leatzmi/tanakhWords.mjs';

const PACK = new URL('../../public/library/packs/uxlc-2.5/', import.meta.url);
const OUT_VERSES = new URL('../../src/data/leatzmi/tanakhVerses.mjs', import.meta.url);
const OUT_WORDS = new URL('../../src/data/leatzmi/tanakhWords.mjs', import.meta.url);
const MIN_OCCURRENCES = 5; // a word met at least this often in Tanakh (by its letters)

// The Aramaic passages are not drawn for מילה בהפתעה (the wheel is for Hebrew words): Daniel 2:4–7:28, Ezra 4:8–6:18
// and 7:12–26, Jeremiah 10:11, and the two words of Genesis 31:47.
const ARAMAIC = { Daniel: [[2, 4, 7, 28]], Ezra: [[4, 8, 6, 18], [7, 12, 7, 26]], Jeremiah: [[10, 11, 10, 11]], Genesis: [[31, 47, 31, 47]] };
const inAramaic = (workId, c, v) => (ARAMAIC[workId] || []).some(([c1, v1, c2, v2]) => (c > c1 || c === c1 && v >= v1) && (c < c2 || c === c2 && v <= v2));

const books = [];
const verses = []; // { bookIndex, chapter, verse, words }
for (const section of TANAKH_SECTIONS) {
  for (const [english, he] of section.books) {
    const workId = english.replace(/ /g, '_');
    const chunk = JSON.parse(gunzipSync(readFileSync(new URL(`${workId}.json.gz`, PACK))).toString('utf8'));
    const counts = chunk.nodes.map(node => node.units.length);
    chunk.nodes.forEach((node, index) => { if (node.n !== index + 1) throw new Error(`${workId}: chapter ${index + 1} out of order`); node.units.forEach((unit, at) => { if (unit.n !== at + 1) throw new Error(`${workId} ${node.n}:${at + 1} out of order`); }); });
    const bookIndex = books.length;
    books.push([workId, he, section.id, counts]);
    for (const node of chunk.nodes) for (const unit of node.units) if (!inAramaic(workId, node.n, unit.n)) verses.push({ bookIndex, chapter: node.n, verse: unit.n, words: verseWords(unit.text) });
  }
}

// How often each word occurs (by its letters), and how often each vocalised form occurs.
const byBase = new Map();
for (const item of verses) for (const word of item.words) {
  const base = baseLetters(word);
  let entry = byBase.get(base);
  if (!entry) byBase.set(base, entry = { count: 0, forms: new Map() });
  entry.count += 1;
  const form = entry.forms.get(word) || { count: 0, first: item };
  form.count += 1;
  entry.forms.set(word, form);
}
const known = new Set([...byBase].filter(([, entry]) => entry.count >= 2).map(([base]) => base));

const words = [];
for (const [base, entry] of byBase) {
  if (entry.count < MIN_OCCURRENCES) continue;
  // The most common vocalisation of these letters (one without a meteg first, it reads more simply); ties by Hebrew
  // order, so the choice is stable.
  const meteg = word => (word.includes('\u05BD') ? 1 : 0);
  const [word, form] = [...entry.forms].sort((a, b) => meteg(a[0]) - meteg(b[0]) || b[1].count - a[1].count || (a[0] < b[0] ? -1 : 1))[0];
  if (!isMeaningfulShape(word) || looksPrefixed(word, known)) continue;
  words.push([word, form.first.bookIndex, form.first.chapter, form.first.verse, base]);
}
words.sort((a, b) => a[1] - b[1] || a[2] - b[2] || a[3] - b[3] || (a[4] < b[4] ? -1 : a[4] > b[4] ? 1 : 0));

mkdirSync(new URL('.', OUT_VERSES), { recursive: true });
const verseTotal = books.reduce((sum, book) => sum + book[3].reduce((a, b) => a + b, 0), 0);
const header = `// Generated by scripts/leatzmi/build-tanakh-surprise.mjs from public/library/packs/uxlc-2.5 (UXLC 2.5, Tanach.us) — do not edit.`;
writeFileSync(OUT_VERSES, `${header}
// ${books.length} books · ${verseTotal} verses: [workId, hebrewName, section, [verses in each chapter]].
export const SOURCE = { pack: 'uxlc-2.5', title: 'כתר לנינגרד (UXLC 2.5)', provider: 'Tanach.us', license: 'uxlc-free' };
export const BOOKS = ${JSON.stringify(books.map(([workId, he, section, counts]) => [workId, he, section, counts]))};
`);
writeFileSync(OUT_WORDS, `${header}
// ${words.length} words: [word, bookIndex (in tanakhVerses BOOKS), chapter, verse] — each word exactly as that verse has it, te'amim removed.
export const WORDS = ${JSON.stringify(words.map(([word, book, chapter, verse]) => [word, book, chapter, verse]))};
`);
console.log(`tanakhVerses.mjs: ${books.length} books, ${verseTotal} verses · tanakhWords.mjs: ${words.length} words`);
