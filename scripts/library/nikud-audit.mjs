#!/usr/bin/env node
// Nikud audit: how much of each bundled work's text is vocalized (מנוקד).
// Reads the pack file(s) of the edition the app reads for every packaged work (registry editions[0]), counts vowel points per Hebrew
// letter in a sample of its text and writes docs/library/nikud-audit.md. Read-only on the packs; it never vocalizes.
//   node scripts/library/nikud-audit.mjs            → writes the report
//   node scripts/library/nikud-audit.mjs --json     → prints the rows as JSON
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { join } from 'node:path';
import { WORKS } from '../../src/data/library/registry.mjs';
import SHNAYIM from '../../src/data/library/shnayimIndex.mjs';

const ROOT = new URL('../../', import.meta.url).pathname;
const PACKS = join(ROOT, 'public/library/packs');
const SAMPLE_LETTERS = 200000;

// Vowel points (sheva…qamats, holam haser, dagesh/mapiq, shin/sin dots, qamats qatan). Cantillation is not nikud.
const NIKUD = /[ְ-ׇּׁׂ]/gu;
const LETTER = /[א-ת]/gu;

export function nikudRatio(text) {
  const letters = (text.match(LETTER) || []).length;
  return { letters, marks: (text.match(NIKUD) || []).length };
}
// Fully vocalized Hebrew carries roughly 0.8–1.1 points per letter; unvocalized text sits near zero (a stray dagesh, a
// quoted verse). "partial" covers editions that vocalize only part of the text (verses quoted inside a commentary…).
export const nikudClass = ratio => (ratio >= 0.5 ? 'yes' : ratio >= 0.08 ? 'partial' : 'no');

function texts(value, out) {
  if (typeof value === 'string') out.push(value);
  else if (Array.isArray(value)) for (const item of value) texts(item, out);
  else if (value && typeof value === 'object') for (const [key, item] of Object.entries(value)) if (!['id', 'workId', 'editionId', 'packId', 'title', 'heTitle', 'label'].includes(key)) texts(item, out);
  return out;
}
const readPack = (packId, file) => {
  const path = join(PACKS, packId, file);
  if (!existsSync(path)) return null;
  const bytes = readFileSync(path);
  return JSON.parse((bytes[0] === 0x1f && bytes[1] === 0x8b ? gunzipSync(bytes) : bytes).toString('utf8'));
};

export function measureFiles(packId, files) {
  let letters = 0;
  let marks = 0;
  for (const file of files) {
    const chunk = readPack(packId, file);
    if (!chunk) continue;
    for (const text of texts(chunk.nodes ?? chunk, [])) {
      const plain = text.replace(/<[^>]+>/g, '');
      const count = nikudRatio(plain);
      letters += count.letters;
      marks += count.marks;
      if (letters >= SAMPLE_LETTERS) break;
    }
    if (letters >= SAMPLE_LETTERS) break;
  }
  const ratio = letters ? marks / letters : 0;
  return { letters, marks, ratio, nikud: letters ? nikudClass(ratio) : 'empty' };
}

export function auditRows() {
  const rows = [];
  // Every packaged work, by the edition the app reads (editions[0]); where a vocalized edition stands in front of a
  // bundled one, the bundled edition is noted as the fallback.
  for (const work of WORKS.filter(item => item.kind === 'pack')) {
    const edition = work.editions[0];
    const files = edition.parts?.length ? edition.parts.map(part => part.file) : [edition.file];
    const fallback = work.editions.find(item => item.role === 'fallback');
    rows.push({
      packId: edition.packId, category: work.primaryCategory, workId: work.workId, heTitle: work.title, title: work.sourceTitle,
      edition: edition.title || '', license: edition.license, fallback: fallback ? `${fallback.title} (${fallback.packId})` : null,
      ...measureFiles(edition.packId, files),
    });
  }
  for (const book of SHNAYIM.books) rows.push({ index: 'shnayim', packId: SHNAYIM.packId, category: 'tanakh', workId: `shnayim.${book.book}`, heTitle: `שניים מקרא · ${book.book}`, title: book.book, edition: `${SHNAYIM.mikra.title} + ${SHNAYIM.targum.title}`, license: SHNAYIM.mikra.license, ...measureFiles(SHNAYIM.packId, [book.file]) });
  return rows;
}

const BEGIN = '<!-- nikud-audit:begin (generated by scripts/library/nikud-audit.mjs) -->';
const END = '<!-- nikud-audit:end -->';
const cell = value => String(value ?? '').replace(/\|/g, '/');
export const auditTable = rows => {
  const by = cls => rows.filter(row => row.nikud === cls).length;
  return [
    BEGIN,
    '',
    `Measured ${rows.length} bundled works (the edition the app reads): **yes ${by('yes')}**, partial ${by('partial')}, **no ${by('no')}**${by('empty') ? `, empty ${by('empty')}` : ''}.`,
    `Sample: up to ${SAMPLE_LETTERS.toLocaleString('en')} Hebrew letters per work; vowel points U+05B0–U+05BC, U+05C1–U+05C2, U+05C7 (te'amim not counted)`,
    'per Hebrew letter. yes ≥ 0.5 (fully vocalized text is ≈ 0.8–0.9), partial 0.08–0.5, no < 0.08.',
    '',
    '| work | workId | pack | edition read | licence | points/letter | nikud | fallback (unvocalized) |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map(row => `| ${cell(row.heTitle)} | \`${row.workId}\` | \`${row.packId}\` | ${cell(row.edition)} | ${row.license} | ${row.ratio.toFixed(2)} | ${row.nikud} | ${cell(row.fallback || '')} |`),
    '',
    END,
  ].join('\n');
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = auditRows();
  if (process.argv.includes('--json')) process.stdout.write(`${JSON.stringify(rows, null, 1)}\n`);
  else {
    const out = join(ROOT, 'docs/library/nikud-audit.md');
    const doc = existsSync(out) ? readFileSync(out, 'utf8') : `# Nikud audit of the bundled library\n\n${BEGIN}\n${END}\n`;
    if (!doc.includes(BEGIN) || !doc.includes(END)) throw new Error(`${out}: no audit markers`);
    writeFileSync(out, `${doc.slice(0, doc.indexOf(BEGIN))}${auditTable(rows)}${doc.slice(doc.indexOf(END) + END.length)}`);
    console.log(`wrote ${out}: ${rows.length} works`);
  }
}
