const normalize = name => String(name || '')
  .replace(/^פרשת\s+/, '')
  .replace(/[׳״'"]/g, '')
  .replace(/\s+/g, ' ')
  .trim();

const LOOKUP = new Map(Object.entries(PARASHOT).map(([name, value]) => [normalize(name), value]));

export function shabbatTableContent(parashaName) {
  const key = normalize(parashaName);
  if (!key) return null;
  const direct = LOOKUP.get(key);
  // Combined readings such as "תזריע־מצורע" fall back to the first available half.
  const entry = direct || key.split(/[־-]/).map(part => LOOKUP.get(normalize(part))).find(Boolean);
  if (!entry) return null;
  
  // Use entry.divreiTorah if available (with extended content), otherwise build from basic fields
  const divreiTorah = entry.divreiTorah || [
    { title: 'נקודת פתיחה', text: entry.summary, type: 'קצר' },
    { title: 'לשולחן המשפחה', text: entry.family, type: 'משפחה' },
    { title: 'לילדים', text: entry.child, type: 'ילדים' },
  ];
  
  return {
    parasha: parashaName,
    summary: entry.summary,
    familyQuestion: entry.family,
    childQuestion: entry.child,
    childContent: entry.childContent || entry.child,
    practicalPoint: entry.practicalPoint || '',
    divreiTorah,
    offline: true,
    source: { ref: entry.ref, text: entry.text },
    quiz: { question: entry.q, answer: entry.a },
  };
}

export const shabbatTableParashaCount = LOOKUP.size;
