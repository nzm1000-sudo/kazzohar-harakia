export function topicDefinition(title) {
  if (HALACHA_TOPIC_INDEX[title]) return HALACHA_TOPIC_INDEX[title];
  const value = String(title || '');
  const queries = [value];
  if (/אורז|מנגו|עוגה|מאכל|מה מברכים/.test(value)) queries.push('ברכות הנהנין', 'ברכה אחרונה');
  if (/שכח.*יעלה|יעלה ויבוא/.test(value)) queries.push('יעלה ויבוא', 'ראש חודש תפילה');
  if (/חימום|מרק|פלטה/.test(value)) queries.push('בישול בשבת', 'שהיה בשבת', 'החזרה בשבת');
  if (/תרופה|חולה/.test(value)) queries.push('רפואה בשבת', 'חולה בשבת');
  if (/סוף זמן|זמן שמע/.test(value)) queries.push('סוף זמן קריאת שמע', 'קריאת שמע');
  if (/תפילת הדרך|נסיעה/.test(value)) queries.push('תפילת הדרך');
  return { id: `topic-${value}`, title: value, queries: [...new Set(queries)], description: `מקורות פתוחים ומאומתים לעיון בנושא ${value}. התוצאות הן מקורות ראשוניים או פרשניים, ולא פסיקה אישית.` };
}

