// Full text may be shown for public-domain works and for CC-BY-NC works (this app is non-commercial; attribution is displayed).
export const APPROVED_HALACHA_PREFIXES = HALACHA_WORKS
  .filter(work => ['public-domain', 'cc-by-nc', 'cc-by-sa'].includes(work.copyrightStatus) && work.referencePrefix)
  .map(work => work.referencePrefix);

export function workForReference(ref = '') {
  return HALACHA_WORKS.find(work => work.referencePrefix && (ref === work.referencePrefix || ref.startsWith(work.referencePrefix + ',') || ref.startsWith(work.referencePrefix + ' ')));
}

export function topicMatches(topic, query) {
  const value = String(query || '').trim().toLocaleLowerCase();
  return !value || [topic.title, ...(topic.aliases || []), ...(topic.children || [])]
    .join(' ').toLocaleLowerCase().includes(value);
}
